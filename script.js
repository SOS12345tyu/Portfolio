$("fsResults").innerHTML = d.formulaStudent.results.map(x => `<li>${x}</li>`).join("");
$("researchTitle").innerHTML = `<a href="${d.research.href}">${d.research.title}</a>`;
$("researchJournal").textContent = d.research.journal;
$("researchSummary").textContent = d.research.summary;
$("doiLink").href = d.research.doi;
