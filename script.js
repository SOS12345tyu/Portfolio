const d = window.PORTFOLIO_DATA;
const $ = (id) => document.getElementById(id);
$("name").textContent = d.name;
$("role").textContent = d.role;
$("intro").textContent = d.intro;
$("resumeLink").href = d.resume;
$("linkedinLink").href = d.linkedin;
$("linkedinLink2").href = d.linkedin;
$("emailLink").href = `mailto:${d.email}`;
$("location").textContent = d.location;
$("footerName").textContent = d.name;
$("metricGrid").innerHTML = d.metrics.map(m => `<article class="metric-card"><strong>${m.value}</strong><span>${m.label}</span><small>${m.detail || ""}</small></article>`).join("");
$("fsTitle").textContent = d.formulaStudent.title;
$("fsSubtitle").textContent = d.formulaStudent.subtitle;
$("fsOverview").textContent = d.formulaStudent.overview;
$("fsHero").src = d.formulaStudent.heroImage;
$("fsResponsibilities").innerHTML = d.formulaStudent.responsibilities.map(x => `<li>${x}</li>`).join("");
$("conceptNote").textContent = d.formulaStudent.conceptClassNote;
